with open(GLOS, "a", encoding="utf-8", newline="\n") as handle:
    handle.write("\n# --- items (table 3) ---\n")
    for r in items:
        name = r["text"]
        got = translate(name)
        if not got:
            continue
        pt, es = got
        handle.write("16\t3\t%s\t%s\t%s\t%s\n" % (r["index"], name, pt, es))
        added += 1

print("item rows added:", added, "of", len(items))
