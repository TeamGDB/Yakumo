# A few suffixes that repeat across the item and weapon tables.
SUFFIX = {
    " Lv1": (" Lv1", " Lv1"),
    " Lv2": (" Lv2", " Lv2"),
    " Lv3": (" Lv3", " Lv3"),
}


def translate(name):
    if name in EXACT:
        return EXACT[name]
    for suffix, (pt, es) in SUFFIX.items():
        if name.endswith(suffix):
            stem = name[: -len(suffix)]
            if stem in EXACT:
                base_pt, base_es = EXACT[stem]
                return base_pt + pt, base_es + es
    return None


